export function createDocumentAgentInstructions(options?: {
  additionalRules?: readonly string[];
}): string {
  const rules = options?.additionalRules
    ?.map((rule) => rule.trim())
    .filter(Boolean);

  if (!rules?.length) return DOCUMENT_AGENT_SYSTEM_INSTRUCTIONS;

  return `${DOCUMENT_AGENT_SYSTEM_INSTRUCTIONS}\n\nこの実行に追加されるルール\n${rules
    .map((rule) => `・${rule}`)
    .join("\n")}`;
}
